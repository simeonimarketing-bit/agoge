test('ospite archivia più PDF offline, evita duplicati, riapre e ripristina gli originali dal backup', async ({ page, browser }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Inizia con i miei dati', exact: true }).click()
  await page.getByRole('button', { name: 'Sala', exact: true }).click()
  await page.getByRole('button', { name: 'Importa PDF', exact: true }).click()
  const pdf = { name: 'Allenamento gennaio.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4 gennaio') }
  await page.getByLabel('Documento PDF').setInputFiles(pdf)
  await expect(page.getByRole('button', { name: 'Leggi PDF', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Leggi PDF', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('non si apre come PDF')
  await page.getByRole('button', { name: 'Conserva nell’archivio' }).click()
  await expect(page.getByRole('heading', { name: 'Archivio programmazioni' })).toBeVisible()
  const altri = [pdf, { name: 'Alimentazione gennaio.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4 alimentazione gennaio') }, { name: 'Non PDF.pdf', mimeType: 'application/pdf', buffer: Buffer.from('non valido') }]
  await page.getByLabel('PDF da archiviare').setInputFiles(altri)
  await expect(page.getByRole('status')).toContainText('1 PDF aggiunti')
  await expect(page.getByRole('status')).toContainText('1 già presenti')
  await expect(page.getByRole('status')).toContainText('non è un PDF valido')
  await page.getByRole('button').filter({ hasText: 'Allenamento gennaio' }).click()
  await page.getByLabel('Tipo di documento').selectOption('allenamento')
  await page.getByLabel('Data del documento').fill('2025-01-01')
  await expect(page.getByRole('link', { name: 'Apri PDF originale' })).toHaveAttribute('href', /^blob:/)
  const pdfDownload = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Scarica', exact: true }).click()
  expect((await pdfDownload).suggestedFilename()).toBe(pdf.name)
  await page.getByRole('button', { name: 'Chiudi', exact: true }).click()
  await page.getByRole('button', { name: '‹ Torna alla Sala' }).click()
  const backupDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Esporta', exact: true }).click()
  const backup = await backupDownload
  const backupPath = (await backup.path())!
  const nuovo = await browser.newContext()
  const p = await nuovo.newPage()
  await p.goto('/')
  await p.getByRole('button', { name: 'Inizia con i miei dati', exact: true }).click()
  await p.getByRole('button', { name: 'Sala', exact: true }).click()
  p.once('dialog', d => d.accept())
  await p.locator('input[type=file][accept="application/json"]').setInputFiles(backupPath)
  await p.getByRole('button', { name: 'Storico', exact: true }).click()
  await p.getByRole('button', { name: 'Programmazioni', exact: true }).click()
  await p.getByRole('button').filter({ hasText: 'Allenamento gennaio' }).click()
  await expect(p.getByRole('link', { name: 'Apri PDF originale' })).toHaveAttribute('href', /^blob:/)
  await expect(p.getByLabel('Data del documento')).toHaveValue('2025-01-01')
  await nuovo.close()
  await page.reload()
  await expect(page.getByText('Nessuna scheda attiva')).toBeVisible()
  await page.getByRole('button', { name: 'Storico', exact: true }).click()
  await page.getByRole('button', { name: 'Programmazioni', exact: true }).click()
  await expect(page.getByRole('button').filter({ hasText: 'Allenamento gennaio' })).toHaveCount(1)
  await expect(page.getByRole('button').filter({ hasText: 'Alimentazione gennaio' })).toHaveCount(1)
  await page.screenshot({ path: 'test-results/archivio-mobile.png', fullPage: true })
})

